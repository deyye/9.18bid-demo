def transform_outline(payload_outline):
    """
    将payload中的大纲结构转换为generate_longform_content所需的格式
    输入: payload中的outline字典（包含details列表）
    输出: 以标题为键、子结构为值的嵌套字典
    """
    def recursive_transform(items):
        result = {}
        for item in items:
            # 递归处理子节点
            if 'children' in item and item['children']:
                children = recursive_transform(item['children'])
            else:
                children = {}
            # 构建当前节点：标题作为键，值包含描述和子结构
            result[item['title']] = {
                'description': item['description'],
                'children': children
            }
        return result
    
    return recursive_transform(payload_outline['details'])

